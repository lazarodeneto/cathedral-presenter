const languageNameCache = new Map<Locale, Intl.DisplayNames>()

export function languageName(language: Locale, uiLocale: Locale): string {
  const fallback =
    LOCALE_OPTIONS.find((option) => option.value === language)?.label ?? language
  try {
    let displayNames = languageNameCache.get(uiLocale)
    if (!displayNames) {
      displayNames = new Intl.DisplayNames([intlLocale(uiLocale)], { type: 'language' })
      languageNameCache.set(uiLocale, displayNames)
    }
    const name = displayNames.of(language)
    return name ? name.charAt(0).toLocaleUpperCase(intlLocale(uiLocale)) + name.slice(1) : fallback
  } catch {
    return fallback
  }
}
